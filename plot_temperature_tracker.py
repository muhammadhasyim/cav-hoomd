#!/usr/bin/env python3
"""
Plot Comprehensive Temperature Tracker Results

This script automatically detects and plots temperature tracker CSV files
generated by the --enable-temp-tracker flag in cavity MD simulations.

The script plots all 6 temperature types:
1. Kinetic temperature (from particle velocities)
2. Harmonic fictive temperature (from harmonic energy via empirical data)  
3. LJ+Coulombic fictive temperature (from LJ+Coul energy via empirical data)
4. Cavity bath temperature (thermostat setting)
5. Molecular bath temperature (thermostat setting)
6. Harmonic equipartition temperature (from harmonic energy via equipartition theorem)
"""

import matplotlib.pyplot as plt
import matplotlib as mpl
import pandas as pd
import numpy as np
import argparse
from pathlib import Path
import glob
import sys
import os

