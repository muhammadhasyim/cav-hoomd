    print(f"\n=== Temperature Statistics ({label}) ===")
    print(f"LJ+Coulomb T_fictive (initial): {df['instantaneous_T_fictive_K'].iloc[0]:.2f} K")
    print(f"LJ+Coulomb T_fictive (final): {df['instantaneous_T_fictive_K'].iloc[-1]:.2f} K")
    
